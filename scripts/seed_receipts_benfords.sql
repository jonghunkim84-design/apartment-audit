-- 전체 건수 및 status 분포
SELECT
  status,
  COUNT(*)                                          AS count,
  SUM(amount)                                       AS total_amount,
  ROUND(COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (), 1) AS pct
FROM receipts
GROUP BY status
ORDER BY count DESC;

-- Benford's Law 검증 — 선두 숫자별 분포
SELECT
  LEFT(amount::text, 1)                              AS leading_digit,
  COUNT(*)                                           AS count,
  ROUND(COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (), 1) AS actual_pct,
  ROUND(LOG(1 + 1.0 / LEFT(amount::text, 1)::int) * 100, 1) AS benford_expected_pct,
  ABS(
    ROUND(COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (), 1) -
    ROUND(LOG(1 + 1.0 / LEFT(amount::text, 1)::int) * 100, 1)
  )                                                  AS deviation
FROM receipts
WHERE amount IS NOT NULL
GROUP BY leading_digit
ORDER BY leading_digit;
