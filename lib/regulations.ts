export const ALL_REGULATIONS: Regulation[] = [
  MANAGEMENT_REGULATION,
  COMMUNITY_CENTER,
  LOST_AND_FOUND,
  FACILITIES,
  PARKING,
]

/**
 * 챗봇 시스템 프롬프트에 삽입할 규정 텍스트 생성
 * 각 규정의 버전·날짜를 함께 출력하여 AI가 최신성을 인지하도록 함
 */
export function buildRegulationsContext(): string {
  const lines: string[] = [
    `=== DMC 센트럴자이 아파트 운영 규정 (최종 업데이트: ${REGULATIONS_LAST_UPDATED}) ===`,
    '※ 아래 규정은 입주자대표회의 의결로 수시 개정될 수 있습니다.',
    '',
  ]

  for (const reg of ALL_REGULATIONS) {
    lines.push(`▣ ${reg.title} [${reg.version} / ${reg.updatedAt} 기준]`)
    lines.push(reg.content.trim())
    lines.push('')
  }

  return lines.join('\n')
}
